import { jest } from '@jest/globals';
import fs from 'node:fs';
import {
  CLOUD_TEMPLATE_FILES,
  CLOUD_TEMPLATE_OUTPUT,
  serializeCloudTemplates,
  createCloudTemplateHandle,
} from '../../../src/core/local/cloud-templates.js';
import { cloudTemplates } from '../../../src/core/cloud/templates.js';

/**
 * Build controlled compiler adapters with a distinct invocation capability.
 * @returns {object} Dependencies and permission observations.
 */
function fixture() {
  const permissions = [];
  const files = Object.fromEntries(
    Object.entries(CLOUD_TEMPLATE_FILES).map(([key, path]) => [
      path,
      `template:${key}`,
    ])
  );
  const deps = {
    readFile: jest.fn(path => files[path]),
    writeFile: jest.fn(async (_permission, path, content) => {
      files[path] = content;
    }),
    formatSource: jest.fn(async source => `formatted:${source}`),
    bindEffectBoundary: jest.fn(async handler => {
      const permission = Object.freeze({ invocation: permissions.length });
      permissions.push(permission);
      return handler(permission);
    }),
  };
  return { deps, files, permissions };
}

test('serializes exact text as a deterministic frozen data module', () => {
  const text = { author: 'line\n"quoted" \\ $& </script> α' };
  expect(serializeCloudTemplates(text)).toBe(
    `// Generated by npm run cloud:templates:refresh; edit the source HTML files.\nexport const cloudTemplates = Object.freeze(${JSON.stringify(text, null, 2)});\n`
  );
  expect(serializeCloudTemplates(text)).toBe(serializeCloudTemplates(text));
});

test('compiles every catalog entry and forwards a fresh permission to writes', async () => {
  const { deps, files, permissions } = fixture();
  const handle = createCloudTemplateHandle(deps);
  expect(deps.readFile).not.toHaveBeenCalled();
  expect(deps.writeFile).not.toHaveBeenCalled();
  const expectedText = Object.fromEntries(
    Object.keys(CLOUD_TEMPLATE_FILES).map(key => [key, `template:${key}`])
  );
  const expected = `formatted:${serializeCloudTemplates(expectedText)}`;
  expect(await handle()).toBe(expected);
  expect(await handle(false)).toBe(expected);
  expect(deps.readFile.mock.calls).toEqual(
    [
      ...Object.values(CLOUD_TEMPLATE_FILES),
      ...Object.values(CLOUD_TEMPLATE_FILES),
    ].map(path => [path])
  );
  expect(deps.formatSource.mock.calls).toEqual([
    [serializeCloudTemplates(expectedText)],
    [serializeCloudTemplates(expectedText)],
  ]);
  expect(permissions).toHaveLength(2);
  expect(permissions[0]).not.toBe(permissions[1]);
  expect(deps.writeFile.mock.calls).toEqual(
    permissions.map(permission => [permission, CLOUD_TEMPLATE_OUTPUT, expected])
  );
  expect(files[CLOUD_TEMPLATE_OUTPUT]).toBe(expected);
});

test('check mode verifies parity without entering an effect boundary or writing', async () => {
  const { deps, files } = fixture();
  const handle = createCloudTemplateHandle(deps);
  const expected = `formatted:${serializeCloudTemplates(Object.fromEntries(Object.keys(CLOUD_TEMPLATE_FILES).map(key => [key, `template:${key}`])))}`;
  files[CLOUD_TEMPLATE_OUTPUT] = expected;
  expect(await handle(true)).toBe(expected);
  expect(deps.bindEffectBoundary).not.toHaveBeenCalled();
  expect(deps.writeFile).not.toHaveBeenCalled();
  expect(deps.readFile).toHaveBeenLastCalledWith(CLOUD_TEMPLATE_OUTPUT);
});

test('drift fails with an actionable command and preserves the existing output', async () => {
  const { deps, files } = fixture();
  files[CLOUD_TEMPLATE_OUTPUT] = 'stale';
  await expect(createCloudTemplateHandle(deps)(true)).rejects.toThrow(
    'Cloud templates are stale; run npm run cloud:templates:refresh'
  );
  expect(files[CLOUD_TEMPLATE_OUTPUT]).toBe('stale');
  expect(deps.bindEffectBoundary).not.toHaveBeenCalled();
  expect(deps.writeFile).not.toHaveBeenCalled();
});

test.each(['read', 'format', 'boundary', 'write'])(
  'preserves %s failures without reporting success',
  async kind => {
    const { deps, files } = fixture();
    const error = new Error(`${kind} unavailable`);
    files[CLOUD_TEMPLATE_OUTPUT] = 'old';
    if (kind === 'read')
      deps.readFile.mockImplementation(() => {
        throw error;
      });
    if (kind === 'format') deps.formatSource.mockRejectedValue(error);
    if (kind === 'boundary') deps.bindEffectBoundary.mockRejectedValue(error);
    if (kind === 'write') deps.writeFile.mockRejectedValue(error);
    await expect(createCloudTemplateHandle(deps)()).rejects.toBe(error);
    expect(files[CLOUD_TEMPLATE_OUTPUT]).toBe('old');
    if (kind !== 'write') expect(deps.writeFile).not.toHaveBeenCalled();
  }
);

test('checked-in generated data exactly matches every authoritative HTML file', () => {
  expect(Object.keys(cloudTemplates)).toEqual(
    Object.keys(CLOUD_TEMPLATE_FILES)
  );
  expect(Object.isFrozen(cloudTemplates)).toBe(true);
  for (const [key, path] of Object.entries(CLOUD_TEMPLATE_FILES)) {
    expect(cloudTemplates[key]).toBe(fs.readFileSync(path, 'utf8'));
  }
});

test('pins the portable source catalog and generated artifact path', () => {
  expect(CLOUD_TEMPLATE_OUTPUT).toBe('src/core/cloud/templates.js');
  expect(CLOUD_TEMPLATE_FILES).toEqual({
    author: 'src/core/cloud/render-author/author-page.html',
    variant: 'src/core/cloud/render-variant/variant-page.html',
    alts: 'src/core/cloud/render-variant/alts-page.html',
    contents: 'src/core/cloud/render-contents/contents-page.html',
    stats: 'src/core/cloud/generate-stats/stats-page.html',
  });
  expect(Object.isFrozen(CLOUD_TEMPLATE_FILES)).toBe(true);
});
