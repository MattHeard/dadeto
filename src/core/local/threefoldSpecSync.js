const NOTION_API_BASE_URL = 'https://api.notion.com/v1';
const NOTION_API_VERSION = '2026-03-11';
const SOURCE_PAGE_ID = '3f5700af-c301-81f0-9c09-cf6293801919';
const SOURCE_PAGE_URL =
  'https://app.notion.com/p/3f5700afc30181f09c09cf6293801919';
const END_HEADING = '## Reference context';

/**
 * Extract the single stable THREEFOLD requirements section from page Markdown.
 * @param {string} markdown Complete Notion page Markdown.
 * @returns {string} Inclusive section from Creative north star to Reference context.
 */
export function extractThreefoldSpecSection(markdown) {
  if (typeof markdown !== 'string' || !markdown.trim()) {
    throw new Error('The Notion page Markdown is empty.');
  }

  const normalized = markdown.replaceAll('\r\n', '\n');
  const startMatches = [
    ...normalized.matchAll(/^## Creative north star\s*$/gm),
  ];
  const endMatches = [...normalized.matchAll(/^## Reference context\s*$/gm)];
  if (startMatches.length !== 1 || endMatches.length !== 1) {
    throw new Error(
      'The Notion page must contain exactly one Creative north star and one Reference context heading.'
    );
  }

  const start = startMatches[0].index;
  const end = endMatches[0].index;
  if (typeof start !== 'number' || typeof end !== 'number' || end <= start) {
    throw new Error(
      'The THREEFOLD Notion source section boundaries are invalid.'
    );
  }

  const sectionEnd = end + END_HEADING.length;
  const section = normalized.slice(start, sectionEnd).trimEnd();
  if (section.length < 1000) {
    throw new Error(
      'The THREEFOLD Notion source section is unexpectedly short.'
    );
  }
  return `${section}\n`;
}

/**
 * Format a generated local copy with stable source metadata.
 * @param {{ markdown: string, lastEditedTime: string }} options Source snapshot.
 * @returns {string} Generated Markdown file.
 */
export function formatThreefoldSpec(options) {
  const section = extractThreefoldSpecSection(options.markdown);
  const timestamp = new Date(options.lastEditedTime);
  if (!Number.isFinite(timestamp.getTime())) {
    throw new Error('Notion page last_edited_time is missing or invalid.');
  }

  return [
    '<!-- Generated from the canonical Notion section; do not edit this file directly. -->',
    `<!-- Source: ${SOURCE_PAGE_URL} -->`,
    `<!-- Source last edited: ${timestamp.toISOString()} -->`,
    '',
    section,
  ].join('\n');
}

/**
 * Check or atomically refresh the generated copy.
 * @param {{
 *   mode: 'check' | 'refresh',
 *   snapshot: { markdown: string, lastEditedTime: string },
 *   targetPath: string,
 *   readFileImpl: (permission: import('../../../types/allow-effects').AllowEffects, path: string, encoding: 'utf8') => Promise<string>,
 *   writeFileImpl: (permission: import('../../../types/allow-effects').AllowEffects, path: string, content: string, encoding: 'utf8') => Promise<void>,
 *   renameImpl: (permission: import('../../../types/allow-effects').AllowEffects, from: string, to: string) => Promise<void>,
 *   unlinkImpl: (permission: import('../../../types/allow-effects').AllowEffects, path: string) => Promise<void>,
 *   bindEffectBoundary: import('../../../types/allow-effects').AllowEffectsBoundary
 * }} options Sync dependencies.
 * @returns {Promise<'current' | 'refreshed'>} Sync result.
 */
export async function synchronizeThreefoldSpec(options) {
  if (options.mode !== 'check' && options.mode !== 'refresh') {
    throw new Error('Choose either check or refresh mode.');
  }
  const expected = formatThreefoldSpec(options.snapshot);
  let current = null;
  try {
    current = await options.bindEffectBoundary(permission =>
      options.readFileImpl(permission, options.targetPath, 'utf8')
    );
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }

  if (current === expected) return 'current';
  if (options.mode === 'check') {
    throw new Error(
      'The local THREEFOLD spec is out of date; run npm run threefold:spec:refresh.'
    );
  }
  const temporaryPath = `${options.targetPath}.tmp`;
  try {
    await options.bindEffectBoundary(permission =>
      options.writeFileImpl(permission, temporaryPath, expected, 'utf8')
    );
    await options.bindEffectBoundary(permission =>
      options.renameImpl(permission, temporaryPath, options.targetPath)
    );
  } catch (error) {
    try {
      await options.bindEffectBoundary(permission =>
        options.unlinkImpl(permission, temporaryPath)
      );
    } catch {
      // Keep the original write error; the temporary file is never the target.
    }
    throw error;
  }
  return 'refreshed';
}

/**
 * Compose the read-only Notion fetch and generated-file synchronization.
 * @param {Omit<Parameters<typeof fetchThreefoldSpecSnapshot>[0], 'token'> & Omit<Parameters<typeof synchronizeThreefoldSpec>[0], 'mode' | 'snapshot' | 'targetPath'>} dependencies Effectful adapters.
 * @returns {(options: { mode: 'check' | 'refresh', token: string, targetPath: string }) => Promise<'current' | 'refreshed'>} Command handler.
 */
export function createThreefoldSpecSyncCommand(dependencies) {
  return async options => {
    const snapshot = await fetchThreefoldSpecSnapshot({
      token: options.token,
      fetchImpl: dependencies.fetchImpl,
      bindEffectBoundary: dependencies.bindEffectBoundary,
      notionVersion: dependencies.notionVersion,
    });
    return synchronizeThreefoldSpec({
      mode: options.mode,
      snapshot,
      targetPath: options.targetPath,
      readFileImpl: dependencies.readFileImpl,
      writeFileImpl: dependencies.writeFileImpl,
      renameImpl: dependencies.renameImpl,
      unlinkImpl: dependencies.unlinkImpl,
      bindEffectBoundary: dependencies.bindEffectBoundary,
    });
  };
}

/**
 * Read a stable Notion page Markdown snapshot and its edit timestamp.
 * @param {{
 *   token: string,
 *   fetchImpl: (permission: import('../../../types/allow-effects').AllowEffects, ...args: Parameters<typeof globalThis.fetch>) => ReturnType<typeof globalThis.fetch>,
 *   bindEffectBoundary: import('../../../types/allow-effects').AllowEffectsBoundary,
 *   notionVersion?: string
 * }} options Read-only API dependencies.
 * @returns {Promise<{ markdown: string, lastEditedTime: string }>} Stable page snapshot.
 */
export async function fetchThreefoldSpecSnapshot(options) {
  const token = requireNonEmptyString(options.token, 'Notion read token');
  const notionVersion = options.notionVersion ?? NOTION_API_VERSION;
  const headers = {
    Authorization: `Bearer ${token}`,
    'Notion-Version': notionVersion,
  };
  const pageUrl = `${NOTION_API_BASE_URL}/pages/${SOURCE_PAGE_ID}`;
  const markdownUrl = `${pageUrl}/markdown`;
  const fetchPageMetadata = () =>
    fetchNotionJson({
      url: pageUrl,
      headers,
      fetchImpl: options.fetchImpl,
      bindEffectBoundary: options.bindEffectBoundary,
      label: 'page metadata',
    });

  const before = await fetchPageMetadata();
  const pageMarkdown = await fetchNotionJson({
    url: markdownUrl,
    headers,
    fetchImpl: options.fetchImpl,
    bindEffectBoundary: options.bindEffectBoundary,
    label: 'page Markdown',
  });
  const after = await fetchPageMetadata();

  if (pageMarkdown.object !== 'page_markdown') {
    throw new Error('Notion returned an invalid page Markdown response.');
  }
  if (
    pageMarkdown.truncated === true ||
    (Array.isArray(pageMarkdown.unknown_block_ids) &&
      pageMarkdown.unknown_block_ids.length > 0)
  ) {
    throw new Error(
      'Notion returned a truncated page; the local spec was not changed.'
    );
  }
  if (
    typeof pageMarkdown.markdown !== 'string' ||
    !pageMarkdown.markdown.trim()
  ) {
    throw new Error('Notion returned an empty page Markdown response.');
  }

  const beforeTimestamp = before.last_edited_time;
  const afterTimestamp = after.last_edited_time;
  if (
    typeof beforeTimestamp !== 'string' ||
    typeof afterTimestamp !== 'string' ||
    beforeTimestamp !== afterTimestamp
  ) {
    throw new Error(
      'The Notion page changed while it was being read; retry the sync.'
    );
  }

  extractThreefoldSpecSection(pageMarkdown.markdown);
  return { markdown: pageMarkdown.markdown, lastEditedTime: afterTimestamp };
}

/**
 * @param {{
 *   url: string,
 *   headers: Record<string, string>,
 *   fetchImpl: (permission: import('../../../types/allow-effects').AllowEffects, ...args: Parameters<typeof globalThis.fetch>) => ReturnType<typeof globalThis.fetch>,
 *   bindEffectBoundary: import('../../../types/allow-effects').AllowEffectsBoundary,
 *   label: string
 * }} options Request options.
 * @returns {Promise<Record<string, unknown>>} Parsed JSON object response.
 */
async function fetchNotionJson(options) {
  if (typeof options.fetchImpl !== 'function') {
    throw new Error('A Notion fetch implementation is required.');
  }
  if (typeof options.bindEffectBoundary !== 'function') {
    throw new Error(
      'An allow-effects boundary is required for Notion requests.'
    );
  }

  let response;
  try {
    response = await options.bindEffectBoundary(permission =>
      options.fetchImpl(permission, options.url, { headers: options.headers })
    );
  } catch {
    throw new Error(
      `Notion ${options.label} request failed before a response was received.`
    );
  }

  if (!response?.ok) {
    throw new Error(
      `Notion ${options.label} request failed with HTTP ${response?.status ?? 'unknown'}.`
    );
  }
  try {
    const body = await response.json();
    if (!body || typeof body !== 'object' || Array.isArray(body)) {
      throw new Error('Notion response is not an object.');
    }
    return /** @type {Record<string, unknown>} */ (body);
  } catch {
    throw new Error(`Notion returned malformed JSON for ${options.label}.`);
  }
}

/**
 * Validate a required string value.
 * @param {unknown} value Candidate string.
 * @param {string} label Error label.
 * @returns {string} Valid trimmed string.
 */
function requireNonEmptyString(value, label) {
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`${label} is required.`);
  }
  return value.trim();
}
