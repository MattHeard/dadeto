/** @typedef {import('../../../types/allow-effects').AllowEffects} AllowEffects */

export const CLOUD_TEMPLATE_FILES = Object.freeze({
  author: 'src/core/cloud/render-author/author-page.html',
  variant: 'src/core/cloud/render-variant/variant-page.html',
  alts: 'src/core/cloud/render-variant/alts-page.html',
  contents: 'src/core/cloud/render-contents/contents-page.html',
  stats: 'src/core/cloud/generate-stats/stats-page.html',
});
export const CLOUD_TEMPLATE_OUTPUT = 'src/core/cloud/templates.js';

/**
 * Serialize checked-in template text as ordinary portable data.
 * @param {Record<string, string>} templates Source template text.
 * @returns {string} JavaScript module before formatting.
 */
export function serializeCloudTemplates(templates) {
  return `// Generated by npm run cloud:templates:refresh; edit the source HTML files.\nexport const cloudTemplates = Object.freeze(${JSON.stringify(templates, null, 2)});\n`;
}

/**
 * Compile or check the exact source templates through injected platform adapters.
 * @param {{
 *   readFile: (path: string) => string,
 *   writeFile: (permission: AllowEffects, path: string, content: string) => Promise<void>,
 *   formatSource: (source: string) => Promise<string>,
 *   bindEffectBoundary: import('../../../types/allow-effects').AllowEffectsBoundary,
 * }} dependencies Source readers, formatter and permission-first writer.
 * @returns {(check?: boolean) => Promise<string>} Compiler command.
 */
export function createCloudTemplateHandle(dependencies) {
  return async (check = false) => {
    const templates = Object.fromEntries(
      Object.entries(CLOUD_TEMPLATE_FILES).map(([key, path]) => [
        key,
        dependencies.readFile(path),
      ])
    );
    const source = await dependencies.formatSource(
      serializeCloudTemplates(templates)
    );
    if (check) {
      if (dependencies.readFile(CLOUD_TEMPLATE_OUTPUT) !== source) {
        throw new Error(
          'Cloud templates are stale; run npm run cloud:templates:refresh'
        );
      }
      return source;
    }
    return dependencies.bindEffectBoundary(async permission => {
      await dependencies.writeFile(permission, CLOUD_TEMPLATE_OUTPUT, source);
      return source;
    });
  };
}
